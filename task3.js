
// Arithmetic Operators
let a = 10;
let b = 5;

console.log("Addition:", a + b);
console.log("Subtraction:", a - b);
console.log("Multiplication:", a * b);
console.log("Division:", a / b);
console.log("Modulus:", a % b);

// Assignment Operators
let x = 10;
x += 5;
console.log("After +=:", x);

x -= 3;
console.log("After -=:", x);

// Comparison Operators
console.log("Equal:", 10 == 10);
console.log("Strict Equal:", 10 === "10");
console.log("Greater Than:", 10 > 5);
console.log("Less Than:", 10 < 5);

// Logical Operators
let age = 20;
console.log("AND:", age > 18 && age < 30);
console.log("OR:", age < 18 || age > 18);
console.log("NOT:", !(age > 18));

// Increment and Decrement
let num = 5;

num++;
console.log("Increment:", num);

num--;
console.log("Decrement:", num);
